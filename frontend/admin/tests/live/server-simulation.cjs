const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { redactError } = require('./support.cjs');
const { ITAM_UI_URL: base, ITAM_DEVICE: device, ITAM_OTHER_DEVICE: otherDevice, ITAM_ARTIFACTS: artifact, ITAM_TEST_PASSWORD: password } = process.env;
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Ho_Chi_Minh' });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    const row = name => page.getByRole('row').filter({ hasText: name });
    const chooseFile = async name => { await row(name).getByRole('radio').check(); };
    await page.goto(base);
    await page.getByRole('heading', { name: 'Chọn nơi làm việc của bạn.' }).waitFor();
    assert.equal(await page.locator('a[href^="/admin"]').count(), 0);
    await page.locator('.machine-card').filter({ hasText: 'WEB-1' }).getByRole('button').click();
    await page.getByLabel('Domain ID').fill('web_employee');
    await page.getByLabel('Mật khẩu', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Đăng nhập máy', exact: true }).click();
    await page.getByRole('tab', { name: 'Chi tiết', exact: true }).waitFor();
    await page.getByText('Windows 11 · mô phỏng', { exact: true }).first().waitFor();
    console.log('PASS choose machine and login without Agent/grant');
    await page.screenshot({ path: path.join(artifact, 'machine-details.png'), fullPage: true, animations: 'disabled' });
    await page.getByRole('tab', { name: 'Phần mềm', exact: true }).click();
    await page.getByText('Ứng dụng mẫu', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(artifact, 'machine-software.png'), fullPage: true, animations: 'disabled' });
    console.log('PASS readonly machine information and software');
    await page.getByRole('tab', { name: 'Desktop / Documents', exact: true }).click();
    await page.getByRole('button', { name: 'Tạo TXT/CSV', exact: true }).click();
    await page.getByLabel('Tên file', { exact: true }).fill('server-note.txt');
    await page.getByRole('dialog').getByRole('button', { name: /OK|Đồng ý/ }).click();
    await row('server-note.txt').waitFor(); await chooseFile('server-note.txt');
    await page.getByRole('button', { name: 'Mở / tải xuống', exact: true }).click();
    await page.getByLabel('Nội dung TXT/CSV').fill('Nội dung lưu trên server 🌱');
    await page.getByRole('button', { name: 'Lưu nội dung', exact: true }).click();
    await page.getByLabel('Nội dung TXT/CSV').waitFor({ state: 'detached' });
    console.log('PASS create edit save TXT through real HTTP/SQL');
    for (const name of ['sample.pdf', 'sample.docx']) {
      await page.getByLabel('Nhập tài liệu', { exact: true }).setInputFiles(path.join(artifact, name));
      await row(name).waitFor();
    }
    await chooseFile('sample.docx');
    const downloading = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Mở / tải xuống', exact: true }).click();
    const download = await downloading; const downloaded = path.join(artifact, 'download.docx');
    await download.saveAs(downloaded);
    assert.deepEqual(fs.readFileSync(downloaded), fs.readFileSync(path.join(artifact, 'sample.docx')));
    console.log('PASS PDF DOCX upload and exact DOCX download');
    await page.reload();
    await page.getByRole('tab', { name: 'Desktop / Documents', exact: true }).click();
    await chooseFile('server-note.txt');
    await page.getByRole('button', { name: 'Mở / tải xuống', exact: true }).click();
    await page.getByLabel('Nội dung TXT/CSV').waitFor();
    assert.equal(await page.getByLabel('Nội dung TXT/CSV').inputValue(), 'Nội dung lưu trên server 🌱');
    console.log('PASS F5 restores correct session and saved file');
    fs.writeFileSync(path.join(artifact, 'api-restart.request'), 'restart');
    await page.waitForFunction(() => true);
    const deadline = Date.now() + 60000;
    while (!fs.existsSync(path.join(artifact, 'api-restart.done'))) {
      if (Date.now() > deadline) throw new Error('API restart timeout');
      await new Promise(r => setTimeout(r, 200));
    }
    await page.reload();
    await page.getByRole('tab', { name: 'Desktop / Documents', exact: true }).click();
    await chooseFile('server-note.txt');
    await page.getByRole('button', { name: 'Mở / tải xuống', exact: true }).click();
    await page.getByLabel('Nội dung TXT/CSV').waitFor();
    assert.equal(await page.getByLabel('Nội dung TXT/CSV').inputValue(), 'Nội dung lưu trên server 🌱');
    console.log('PASS API restart retains metadata content and session');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('tab', { name: 'Chi tiết', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(artifact, 'machine-mobile.png'), fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: 'Đăng xuất / Đổi máy', exact: true }).click();
    await page.locator('.machine-card').filter({ hasText: 'WEB-2' }).getByRole('button').click();
    await page.getByLabel('Domain ID').fill('web_employee');
    await page.getByLabel('Mật khẩu', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Đăng nhập máy', exact: true }).click();
    await page.getByRole('tab', { name: 'Desktop / Documents', exact: true }).click();
    assert.equal(await row('server-note.txt').count(), 0);
    assert.equal(new URL(page.url()).pathname, `/machines/${otherDevice}/desktop`);
    console.log('PASS other active machine available with isolated files and mobile layout');
    await page.getByRole('button', { name: 'Đăng xuất / Đổi máy', exact: true }).click();
    assert.equal(await page.evaluate(() => sessionStorage.getItem('itdesk.accessToken')), null);
    assert.deepEqual(errors, []);
    console.log('PASS logout clears credentials; no browser errors');
  } finally { await browser.close(); }
})().catch(e => { console.error(redactError(e)); process.exitCode = 1; });
